STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900]

def lum(h):
    c = [int(h[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    c = [x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4 for x in c]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]

def ratio(a, b):
    la, lb = sorted((lum(a), lum(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)

failed = False
for site, modes in PALETTES.items():
    css = [f"/* Generated by scripts/palettes.py: {site}. site colours; edit there, not here. */", "@theme {"]
    def block(m):
        p = modes[m]
        out = [f"  --color-white: {p['white']};"]
        out += [f"  --color-stone-{s}: {v};" for s, v in zip(STEPS, p["stone"])]
        out += [f"  --color-teal-{s}: {v};" for s, v in p["teal"].items()]
        return out
    css += block("light") + ["}", "", "html.dark {"] + block("dark") + ["}", ""]
    open(f"sites/{site}/src/palette.css", "w").write("\n".join(css))

    for m, p in modes.items():
        st = dict(zip(STEPS, p["stone"])); t = p["teal"]; card = p["white"]; page = st[50]
        checks = [
            ("body text on page", st[900], page, 7),
            ("secondary text (stone-500) on card", st[500], card, 4.5),
            ("secondary text (stone-500) on page", st[500], page, 4.5),
            ("stone-600 on card", st[600], card, 4.5),
            ("button text on teal-700", card, t["700"], 4.5),
            ("button text on teal-800 (hover)", card, t["800"], 4.5),
            ("links (teal-800) on card", t["800"], card, 4.5),
            ("result (teal-900) on teal-50", t["900"], t["50"], 7),
            ("secondary text on teal-50", st[600], t["50"], 4.5),
            ("input border (stone-300) on card", st[300], card, 1.3),
        ]
        for name, fg, bg, need in checks:
            r = ratio(fg, bg); ok = r >= need; failed |= not ok
            print(f"{site} {m:5} {'ok  ' if ok else 'FAIL'} {r:5.2f} (≥{need}) {name}")
sys.exit(1 if failed else 0)
