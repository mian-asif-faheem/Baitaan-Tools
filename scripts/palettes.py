def rgba(h, a):
    n = int(h[1:], 16)
    return f"rgba({n >> 16},{(n >> 8) & 255},{n & 255},{a})"

def mix(a, b, w):
    """a mixed into b at weight w, as #rrggbb."""
    ca = [int(a[i:i + 2], 16) for i in (1, 3, 5)]; cb = [int(b[i:i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join(f"{round(x * w + y * (1 - w)):02x}" for x, y in zip(ca, cb))

